using TokenMojo.Core;

namespace TokenMojo.Core.Tests;

public sealed class TranscriptTitleTests
{
    private const string Snapshot = """{"type":"file-history-snapshot","snapshot":{}}""";

    [Fact]
    public void FirstPrompt_TypedPrompt_IsTheTitle()
    {
        // Arrange
        string[] lines = [Snapshot, User("\"Fix the login redirect\""), User("\"And the logout one\"")];

        // Act / Assert
        Assert.Equal("Fix the login redirect", TranscriptTitle.FirstPrompt(lines));
    }

    [Fact]
    public void FirstPrompt_SkipsMetaLinesToolResultsAndLocalCommandOutput()
    {
        // Arrange
        string[] lines =
        [
            """{"type":"user","isMeta":true,"message":{"role":"user","content":"Base directory for this skill"}}""",
            User("""[{"type":"tool_result","tool_use_id":"t1","content":"ok"}]"""),
            User("\"<local-command-caveat>Caveat: the messages below were generated by the user</local-command-caveat>\""),
            User("\"<local-command-stdout></local-command-stdout>\""),
            User("""[{"type":"text","text":"Plan the settings window"}]"""),
        ];

        // Act / Assert
        Assert.Equal("Plan the settings window", TranscriptTitle.FirstPrompt(lines));
    }

    [Fact]
    public void FirstPrompt_SlashCommand_IsShownAsTypedButClearIsSkipped()
    {
        // Arrange
        string[] lines =
        [
            User("\"<command-name>/clear</command-name>\\n<command-message>clear</command-message>\\n<command-args></command-args>\""),
            User("\"<command-name>/standup</command-name>\\n<command-message>standup</command-message>\\n<command-args>for Monday</command-args>\""),
        ];

        // Act / Assert
        Assert.Equal("/standup for Monday", TranscriptTitle.FirstPrompt(lines));
    }

    [Fact]
    public void FirstPrompt_NoPromptYet_IsNull()
    {
        // Act / Assert
        Assert.Null(TranscriptTitle.FirstPrompt([Snapshot, "not json", "{\"type\":\"user\"}"]));
    }

    [Theory]
    [InlineData("review pr https://github.com/octo/widgets/pull/1515#pullrequestreview-1", "review pr octo/widgets#1515")]
    [InlineData("look at https://github.com/octo/widgets/issues/7", "look at octo/widgets#7")]
    [InlineData("plan https://linear.app/acme/issue/eng-42/fix-the-login", "plan ENG-42")]
    [InlineData("first line\n\n  second   line", "first line second line")]
    public void Shorten_LinksAndWhitespace(string prompt, string expected)
    {
        // Act / Assert
        Assert.Equal(expected, TranscriptTitle.Shorten(prompt));
    }

    [Fact]
    public void Shorten_LongPrompt_IsCutWithAnEllipsis()
    {
        // Act
        string title = TranscriptTitle.Shorten(new string('a', 150));

        // Assert
        Assert.Equal(100, title.Length);
        Assert.EndsWith("…", title);
    }

    private static string User(string contentJson) => """{"type":"user","message":{"role":"user","content":""" + contentJson + "}}";
}
